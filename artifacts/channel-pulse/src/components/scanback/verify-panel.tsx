import { customerLabel, maskCustomerText } from "@/lib/customer-display";
import { TRACKING_ROW, TrackingLegend, TrackingTag, trackingColorOf } from "./tracking";
import { useEffect, useMemo, useRef, useState } from "react";
import {
  getExportScanbackBatchUrl,
  getExportScanbackDraftUrl,
  useApproveScanbackClaim,
  useVerifyScanbackClaim,
  type Reseller,
  type ScanbackBatch,
  type ScanbackDraft,
  type ScanbackImport,
  type ScanbackProgram,
} from "@workspace/api-client-react";
import { Button } from "@/components/ui/button";
import { Input } from "@/components/ui/input";
import { Label } from "@/components/ui/label";
import { Checkbox } from "@/components/ui/checkbox";
import { Select, SelectContent, SelectItem, SelectTrigger, SelectValue } from "@/components/ui/select";
import { Table, TableBody, TableCell, TableHead, TableHeader, TableRow } from "@/components/ui/table";
import {
  AlertDialog, AlertDialogAction, AlertDialogCancel, AlertDialogContent, AlertDialogDescription,
  AlertDialogFooter, AlertDialogHeader, AlertDialogTitle,
} from "@/components/ui/alert-dialog";
import { CheckCircle2, Download, Eye, EyeOff, RefreshCw, ShieldCheck } from "lucide-react";
import { SectionEmpty, StatusPill, errorMessage, formatCents, formatDate, formatDateTime, useRefreshWorkspace } from "./shared";

export function VerifyPanel({
  programs, imports, drafts, resellers, onApproved, preset, onOpenSerial,
}: {
  onOpenSerial?: (serial: string) => void;
  programs: ScanbackProgram[]; imports: ScanbackImport[]; drafts: ScanbackDraft[]; resellers: Reseller[];
  onApproved: (b: ScanbackBatch) => void;
  /** Deep-link preselection from the Upload Center. */
  preset?: { reportId?: string; resellerId?: number; promotionId?: string } | null;
}) {
  const refresh = useRefreshWorkspace();
  const verify = useVerifyScanbackClaim();
  const approve = useApproveScanbackClaim();
  const [programId, setProgramId] = useState("");
  const [accountId, setAccountId] = useState("");
  const [claimImportId, setClaimImportId] = useState("");
  const [draft, setDraft] = useState<ScanbackDraft | null>(null);
  const [selected, setSelected] = useState<Set<number>>(new Set());
  const [error, setError] = useState<string | null>(null);
  const [confirmOpen, setConfirmOpen] = useState(false);
  const [reference, setReference] = useState("");
  const [approved, setApproved] = useState<ScanbackBatch | null>(null);
  const [showNotDdRange, setShowNotDdRange] = useState(false);
  const [overrideOpen, setOverrideOpen] = useState(false);
  const handledAutoDrafts = useRef(new Set<string>());

  const program = programs.find((p) => p.id === programId);
  const activePrograms = programs.filter((p) => !p.archived);
  const claimImports = imports.filter((i) => i.kind === "claim" && i.state === "committed");
  const resById = new Map(resellers.map((r) => [r.id, r]));
  const accounts = program ? resellers.filter((r) => program.customerIds.includes(r.id)) : [];
  const autoDrafts = useMemo(
    () => drafts.filter((item) => item.autoGenerated).sort((a, b) => b.createdAt.localeCompare(a.createdAt)),
    [drafts],
  );
  const recentDrafts = drafts.filter((item) => !item.autoGenerated)
    .sort((a, b) => b.createdAt.localeCompare(a.createdAt)).slice(0, 8);

  const presetKey = preset ? JSON.stringify(preset) : "";
  const presetApplied = useRef("");

  const showDraft = (d: ScanbackDraft) => {
    setDraft(d);
    setSelected(new Set(d.results.filter((r) => r.include && r.selectable).map((r) => r.rowIndex)));
  };

  const restore = (d: ScanbackDraft) => {
    setError(null); setApproved(null);
    setProgramId(d.settings.programId); setAccountId(String(d.settings.accountId));
    setClaimImportId(d.settings.claimImportId);
    showDraft(d);
  };
  const openDraft = (d: ScanbackDraft) => {
    if (d.autoGenerated) handledAutoDrafts.current.add(d.id);
    restore(d);
  };

  useEffect(() => {
    if (!preset || presetApplied.current === presetKey) return;
    presetApplied.current = presetKey;
    const automatic = autoDrafts.find((item) =>
      (!preset.reportId || item.settings.claimImportId === preset.reportId) &&
      (preset.resellerId == null || item.settings.accountId === preset.resellerId) &&
      (!preset.promotionId || item.settings.programId === preset.promotionId));
    if (automatic) {
      handledAutoDrafts.current.add(automatic.id);
      restore(automatic);
      return;
    }
    setOverrideOpen(true);
    if (preset.promotionId && programs.some((item) => item.id === preset.promotionId)) setProgramId(preset.promotionId);
    if (preset.resellerId != null) setAccountId(String(preset.resellerId));
    if (preset.reportId && imports.some((item) => item.id === preset.reportId)) setClaimImportId(preset.reportId);
  }, [presetKey, autoDrafts]); // eslint-disable-line react-hooks/exhaustive-deps

  useEffect(() => {
    if (presetKey || draft) return;
    const next = autoDrafts.find((item) => !handledAutoDrafts.current.has(item.id));
    if (next) {
      handledAutoDrafts.current.add(next.id);
      restore(next);
    }
  }, [autoDrafts, presetKey, draft]); // eslint-disable-line react-hooks/exhaustive-deps

  const settingsDirty = !!draft && (
    draft.settings.programId !== programId || String(draft.settings.accountId) !== accountId ||
    draft.settings.claimImportId !== claimImportId);
  const selectionDirty = useMemo(() => {
    if (!draft) return false;
    const inc = draft.results.filter((r) => r.include && r.selectable).map((r) => r.rowIndex);
    return inc.length !== selected.size || inc.some((i) => !selected.has(i));
  }, [draft, selected]);
  const dirty = settingsDirty || selectionDirty;

  const run = (withSelection: boolean) => {
    setError(null); setApproved(null);
    const selectedProgram = programs.find((item) => item.id === programId);
    if (!selectedProgram || !accountId || !claimImportId) return setError("Choose a promotion, customer and committed serial report.");
    verify.mutate(
      { data: {
        programId, accountId: Number(accountId), claimImportId, basis: "sell",
        from: selectedProgram.start.slice(0, 10), to: selectedProgram.end.slice(0, 10),
        ...(withSelection && draft && !settingsDirty ? { draftId: draft.id, selectedRows: [...selected].sort((a, b) => a - b) } : {}),
      } },
      { onSuccess: (d) => { showDraft(d); refresh(); }, onError: (e) => setError(errorMessage(e)) },
    );
  };

  const doApprove = () => {
    if (!draft || approve.isPending) return;
    approve.mutate(
      { data: { draftId: draft.id, token: draft.token, reference: reference.trim() } },
      {
        onSuccess: (b) => {
          if (draft.autoGenerated) handledAutoDrafts.current.add(draft.id);
          setConfirmOpen(false); setApproved(b); setDraft(null); setReference(""); refresh(); onApproved(b);
        },
        onError: (e) => { setConfirmOpen(false); setError(errorMessage(e)); },
      },
    );
  };

  const counts = draft ? {
    eligible: draft.results.filter((r) => r.status === "eligible").length,
    review: draft.results.filter((r) => r.status === "review").length,
    rejected: draft.results.filter((r) => r.status === "rejected").length,
  } : null;
  const notDdRangeCount = draft?.results.filter((r) => r.notDdRange).length ?? 0;
  const visibleResults = draft?.results.filter((r) => showNotDdRange || !r.notDdRange) ?? [];
  const canApprove = !!draft && !dirty && draft.totalCents > 0 && !verify.isPending && !approve.isPending;
  const unmatchedReports = imports.filter((item) =>
    item.kind === "claim" && item.state === "committed" &&
    item.warnings.some((warning) => warning.startsWith("Automatic promotion matching:")),
  );

  return (
    <div className="space-y-4">
      {unmatchedReports.length > 0 && (
        <div role="status" className="rounded-lg border border-amber-300 bg-amber-50 px-4 py-3 text-sm text-amber-900">
          {unmatchedReports.length} committed serial report{unmatchedReports.length === 1 ? "" : "s"} contain rows without one unique customer promotion match. Use the override to review those rows.
        </div>
      )}
      {autoDrafts.length > 0 && (
        <div className="rounded-lg border bg-background">
          <div className="flex items-center justify-between border-b px-4 py-2">
            <p className="text-xs font-semibold uppercase tracking-wider text-slate-600">Automatic drafts to review</p>
            <span className="text-xs text-slate-500">{autoDrafts.length} pending</span>
          </div>
          <div className="grid max-h-72 gap-2 overflow-y-auto p-3 sm:grid-cols-2 xl:grid-cols-3">
            {autoDrafts.map((item) => {
              const itemProgram = programs.find((p) => p.id === item.settings.programId);
              const itemImport = imports.find((i) => i.id === item.settings.claimImportId);
              const itemAccount = resById.get(item.settings.accountId);
              const active = draft?.id === item.id;
              return (
                <button key={item.id} type="button" onClick={() => openDraft(item)}
                  aria-current={active ? "true" : undefined}
                  data-testid={`button-auto-draft-${item.id}`}
                  className={`min-w-0 rounded-md border px-3 py-2 text-left transition-colors ${active ? "border-cyan-500 bg-cyan-50" : "hover:bg-slate-50"}`}>
                  <span className="block truncate text-sm font-medium">{itemProgram?.name ?? "Promotion"} · {customerLabel(itemAccount?.code ?? item.settings.accountId)}</span>
                  <span className="mt-1 block truncate text-xs text-slate-500">{itemImport?.name ?? "Serial report"} · {item.results.length} serials</span>
                  <span className="mt-1 block font-mono text-xs font-semibold tabular-nums">{formatCents(item.totalCents)}</span>
                </button>
              );
            })}
          </div>
        </div>
      )}

      <div className="rounded-lg border bg-background">
        <div className="flex flex-wrap items-center justify-between gap-2 px-4 py-3">
          <div>
            <p className="text-sm font-medium">Automatic matching uses customer sold date</p>
            <p className="text-xs text-muted-foreground">Claims are DD invoiced price ex GST minus promotion GTM Buy Ex.</p>
          </div>
          <Button variant="outline" size="sm" type="button" aria-expanded={overrideOpen}
            data-testid="button-toggle-verify-override" onClick={() => setOverrideOpen((open) => !open)}>
            {overrideOpen ? "Close override" : "Override promotion, customer or file"}
          </Button>
        </div>
        {overrideOpen && (
          <div className="grid gap-3 border-t p-4 md:grid-cols-3">
            <div className="space-y-1">
              <Label className="text-xs">Promotion</Label>
              <Select value={programId} onValueChange={(v) => {
                setProgramId(v);
                const selectedProgram = programs.find((x) => x.id === v);
                if (!selectedProgram || !selectedProgram.customerIds.includes(Number(accountId))) setAccountId("");
              }}>
                <SelectTrigger data-testid="select-verify-program"><SelectValue placeholder="Choose promotion" /></SelectTrigger>
                <SelectContent>{activePrograms.map((p) => <SelectItem key={p.id} value={p.id}>{p.name}</SelectItem>)}</SelectContent>
              </Select>
            </div>
            <div className="space-y-1">
              <Label className="text-xs">Customer</Label>
              <Select value={accountId} onValueChange={setAccountId} disabled={!program}>
                <SelectTrigger data-testid="select-verify-account"><SelectValue placeholder="Choose customer" /></SelectTrigger>
                <SelectContent>{accounts.map((r) => <SelectItem key={r.id} value={String(r.id)}>{customerLabel(r.code)}</SelectItem>)}</SelectContent>
              </Select>
            </div>
            <div className="space-y-1">
              <Label className="text-xs">Committed serial report</Label>
              <Select value={claimImportId} onValueChange={setClaimImportId}>
                <SelectTrigger data-testid="select-verify-import"><SelectValue placeholder={claimImports.length ? "Choose report" : "Commit a serial report first"} /></SelectTrigger>
                <SelectContent>{claimImports.map((i) => <SelectItem key={i.id} value={i.id}>{i.name} ({i.recordCount})</SelectItem>)}</SelectContent>
              </Select>
            </div>
            <div className="md:col-span-3">
              <Button onClick={() => run(false)} disabled={verify.isPending} data-testid="button-run-verify">
                <ShieldCheck className="mr-1.5 h-4 w-4" /> {verify.isPending ? "Verifying..." : "Run override"}
              </Button>
            </div>
          </div>
        )}
      </div>

      {error && <div data-testid="text-verify-error" className="rounded-md bg-rose-50 px-3 py-2 text-sm text-rose-700">{error}</div>}

      {approved && (
        <div data-testid="card-approval-success" className="flex flex-wrap items-center gap-3 rounded-lg border border-emerald-300 bg-emerald-50 px-4 py-3">
          <CheckCircle2 className="h-5 w-5 text-emerald-700" />
          <div className="flex-1 text-sm text-emerald-900">
            Claim decision <span className="font-semibold">{approved.reference}</span> approved: {approved.approvedCount} serials, {formatCents(approved.totalCents)}.
            No payment has been made; this records the claim decision only.
          </div>
          <Button size="sm" variant="outline" asChild><a href={getExportScanbackBatchUrl(approved.id, "xlsx")}>Statement (XLSX)</a></Button>
        </div>
      )}

      {!draft ? (
        <div className="space-y-3">
          <SectionEmpty title="No automatic draft ready" body="New committed serial reports create drafts automatically when a sold date and customer match exactly one active promotion. Use an override only when matching needs correction." />
          {recentDrafts.length > 0 && (
            <div className="rounded-lg border bg-background">
              <p className="border-b px-4 py-2 text-xs font-semibold uppercase tracking-wider text-slate-500">Saved manual drafts</p>
              {recentDrafts.map((d) => (
                <button key={d.id} type="button" onClick={() => restore(d)} data-testid={`button-restore-draft-${d.id}`}
                  className="flex w-full items-center justify-between gap-2 border-b px-4 py-2 text-left text-sm last:border-0 hover:bg-cyan-50/50">
                  <span>{programs.find((p) => p.id === d.settings.programId)?.name ?? "Promotion"} &middot; {customerLabel(resById.get(d.settings.accountId)?.code ?? d.settings.accountId)}</span>
                  <span className="font-mono text-xs text-slate-500">{formatCents(d.totalCents)} &middot; {formatDateTime(d.createdAt)}</span>
                </button>
              ))}
            </div>
          )}
        </div>
      ) : (
        <div className="rounded-lg border bg-background">
          <div className="flex flex-wrap items-center gap-4 border-b px-4 py-3">
            <div className="flex-1 min-w-[200px]">
              <p className="text-xs font-semibold uppercase tracking-wider text-amber-700">
                {draft.autoGenerated ? "Automatic draft · not approved" : "Manual override · not approved"}
              </p>
              <p className="text-sm text-slate-600">
                {program?.name ?? "Promotion"} · Customer sold date · {formatDate(program?.start)} to {formatDate(program?.end)}
                {counts && <> &middot; {counts.eligible} eligible, {counts.review} review, {counts.rejected} rejected</>}
              </p>
            </div>
            <div className="text-right">
              <p className="text-xs text-slate-500">Selected total</p>
              <p className="font-mono text-xl font-semibold tabular-nums" data-testid="text-draft-total">{formatCents(draft.totalCents)}</p>
            </div>
            <div className="flex flex-wrap gap-2">
              <Button variant="outline" size="sm" asChild data-testid="link-draft-export">
                <a href={getExportScanbackDraftUrl(draft.id)}><Download className="mr-1 h-3.5 w-3.5" /> Draft statement</a>
              </Button>
              <Button variant="outline" size="sm" onClick={() => run(true)} disabled={verify.isPending || !dirty} data-testid="button-recheck">
                <RefreshCw className="mr-1 h-3.5 w-3.5" /> Recheck selection
              </Button>
              <Button size="sm" onClick={() => setConfirmOpen(true)} disabled={!canApprove} data-testid="button-approve">Approve claim</Button>
            </div>
          </div>
          {dirty && <p className="border-b bg-amber-50 px-4 py-2 text-xs text-amber-800">Selection or settings changed. Recheck before approving{settingsDirty ? " (settings changed - this will run a fresh verification)" : ""}.</p>}
          <TrackingLegend />
          {notDdRangeCount > 0 && (
            <div className="flex items-center justify-between gap-3 border-b bg-slate-50 px-4 py-2 text-sm" data-testid="not-dd-range-group">
              <span className="text-slate-700">Not DD-range: {notDdRangeCount.toLocaleString()} serials</span>
              <Button type="button" size="sm" variant="outline" aria-expanded={showNotDdRange}
                data-testid="toggle-not-dd-range" onClick={() => setShowNotDdRange((value) => !value)}>
                {showNotDdRange ? <EyeOff className="mr-1 h-3.5 w-3.5" /> : <Eye className="mr-1 h-3.5 w-3.5" />}
                {showNotDdRange ? "Hide rows" : "Show rows"}
              </Button>
            </div>
          )}
          <div className="max-h-[560px] overflow-auto">
            <Table>
              <TableHeader><TableRow>
                <TableHead className="w-8" /><TableHead>Status</TableHead><TableHead>Serial</TableHead><TableHead>SKU</TableHead><TableHead>Sale date</TableHead>
                <TableHead>Invoiced to</TableHead><TableHead>Invoice</TableHead><TableHead className="text-right">Invoiced ex GST (customer paid)</TableHead><TableHead className="text-right">GTM Buy Ex</TableHead>
                <TableHead className="text-right">Claim</TableHead><TableHead>Reason</TableHead>
              </TableRow></TableHeader>
              <TableBody>
                {visibleResults.map((r) => { const tc = trackingColorOf(r); return (
                  <TableRow key={r.rowIndex} data-testid={`row-result-${r.rowIndex}`} data-tracking={tc} className={TRACKING_ROW[tc]}>
                    <TableCell>
                      {r.selectable && (
                        <Checkbox checked={selected.has(r.rowIndex)} data-testid={`checkbox-result-${r.rowIndex}`}
                          onCheckedChange={(c) => setSelected((s) => { const n = new Set(s); if (c) n.add(r.rowIndex); else n.delete(r.rowIndex); return n; })} />
                      )}
                    </TableCell>
                    <TableCell><StatusPill status={r.status} /><span className="mt-0.5 block"><TrackingTag color={tc} /></span></TableCell>
                    <TableCell className="font-mono text-xs">{onOpenSerial ? <button type="button" className="underline decoration-dotted underline-offset-2 hover:text-cyan-700" onClick={() => onOpenSerial(r.serial)} data-testid={`button-serial-trail-${r.rowIndex}`} title="Open serial trail">{r.serial}</button> : r.serial}{r.quantity !== 1 && <span className="ml-1 text-amber-700">x{r.quantity}</span>}</TableCell>
                    <TableCell className="font-mono text-xs">{r.sku}</TableCell>
                    <TableCell className="text-xs">{r.date || "-"}</TableCell>
                    <TableCell className="text-xs">{r.invoicedAccountId != null ? customerLabel(resById.get(r.invoicedAccountId)?.code ?? r.invoicedAccountId) : r.invoicedTo ? maskCustomerText(r.invoicedTo) : "-"}</TableCell>
                    <TableCell className="text-xs"><span className="font-mono">{r.invoice || "-"}</span>{r.invoiceDate && <span className="block text-slate-500">{r.invoiceDate}</span>}</TableCell>
                    <TableCell className="text-right font-mono text-xs">{formatCents(r.unitPriceCents)}</TableCell>
                    <TableCell className="text-right font-mono text-xs">{formatCents(r.gtmBuyCents)}{r.costCents != null && <span className="block text-[10px] font-sans text-slate-400" title="Our cost, reference only, not the claim basis">our cost (ref) {formatCents(r.costCents)}</span>}</TableCell>
                    <TableCell className="text-right font-mono text-xs font-semibold"
                      title={r.status === "eligible" ? "Payable claim amount" : "Calculated difference only; this blocked serial is not payable"}>
                      {formatCents(r.unitPriceCents != null && r.gtmBuyCents != null ? r.unitPriceCents - r.gtmBuyCents : r.amountCents)}
                    </TableCell>
                    <TableCell className="max-w-xs text-xs text-slate-600">{maskCustomerText(r.reason)}</TableCell>
                  </TableRow>
                ); })}
              </TableBody>
            </Table>
          </div>
        </div>
      )}

      <AlertDialog open={confirmOpen} onOpenChange={(o) => !approve.isPending && setConfirmOpen(o)}>
        <AlertDialogContent>
          <AlertDialogHeader>
            <AlertDialogTitle>Approve {draft ? formatCents(draft.totalCents) : ""} claim?</AlertDialogTitle>
            <AlertDialogDescription>
              This permanently records the selected serials as claimed. Each serial can never be paid again under any promotion.
              Eligibility and caps are rechecked on the server. No bank transfer is made.
            </AlertDialogDescription>
          </AlertDialogHeader>
          <div className="space-y-1.5">
            <Label htmlFor="sb-ref">Claim reference</Label>
            <Input id="sb-ref" value={reference} onChange={(e) => setReference(e.target.value)} placeholder="e.g. SB-2025-031" data-testid="input-approve-reference" />
          </div>
          <AlertDialogFooter>
            <AlertDialogCancel disabled={approve.isPending}>Cancel</AlertDialogCancel>
            <AlertDialogAction disabled={!reference.trim() || approve.isPending} data-testid="button-confirm-approve"
              onClick={(e) => { e.preventDefault(); doApprove(); }}>
              {approve.isPending ? "Approving..." : "Approve claim"}
            </AlertDialogAction>
          </AlertDialogFooter>
        </AlertDialogContent>
      </AlertDialog>
    </div>
  );
}
